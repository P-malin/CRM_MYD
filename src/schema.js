// Schema ฐานข้อมูล (PostgreSQL) — รันซ้ำได้ปลอดภัย (IF NOT EXISTS)
const { DEFAULT_JOB_TYPES, DEFAULT_JOB_STATUSES } = require('./constants');

const sqlStr = (v) => `'${String(v).replace(/'/g, "''")}'`;
// VALUES (...) ของประเภทงานเริ่มต้น ใช้ตอน migrate และตอนสมัครร้านใหม่
const DEFAULT_JOB_TYPES_VALUES = DEFAULT_JOB_TYPES.map(
  (t, i) => `(${sqlStr(t.name)}, ${sqlStr(t.description)}, ${t.requires_detail ? 'true' : 'false'}, ${i + 1})`,
).join(',\n    ');

// VALUES (...) ของสถานะงานเริ่มต้น
const DEFAULT_JOB_STATUSES_VALUES = DEFAULT_JOB_STATUSES.map(
  (t, i) => `(${sqlStr(t.name)}, ${sqlStr(t.description)}, ${sqlStr(t.color)}, ${sqlStr(t.kind)}, ${i + 1})`,
).join(',\n    ');
// CASE แปลงสถานะเดิม (ข้อความ) → ชื่อสถานะใน master
const legacyCase = (col) =>
  `CASE ${col} ${DEFAULT_JOB_STATUSES.filter((t) => t.legacy).map((t) => `WHEN ${sqlStr(t.legacy)} THEN ${sqlStr(t.name)}`).join(' ')} END`;

// เพิ่มเลขนี้ทุกครั้งที่แก้ schema เพื่อให้ระบบรัน migration ใหม่
const SCHEMA_VERSION = 5;
const TABLES = ['schema_version', 'tenants', 'users', 'sessions', 'customers', 'job_types', 'job_statuses', 'jobs', 'job_status_logs', 'payments'];

const SCHEMA = `
CREATE TABLE IF NOT EXISTS schema_version (
  version     integer PRIMARY KEY,
  applied_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tenants (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  phone       text,
  email       text,
  address     text,
  tax_id      text,
  job_seq     integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name          text NOT NULL,
  email         text NOT NULL,
  password_hash text NOT NULL,
  role          text NOT NULL CHECK (role IN ('owner','admin','staff')),
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_key ON users (lower(email));
CREATE INDEX IF NOT EXISTS idx_users_tenant ON users(tenant_id);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash  text PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at  timestamptz NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS customers (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name        text NOT NULL,
  company     text,
  phone       text,
  email       text,
  line_id     text,
  address     text,
  tax_id      text,
  note        text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_customers_tenant ON customers(tenant_id);

-- master ประเภทงาน (แยกต่อร้าน)
CREATE TABLE IF NOT EXISTS job_types (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name            text NOT NULL,
  description     text,
  requires_detail boolean NOT NULL DEFAULT false,
  sort_order      integer NOT NULL DEFAULT 0,
  active          boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, name)
);

-- master สถานะงาน (แยกต่อร้าน) — kind บอกระบบว่าสถานะนี้อยู่ช่วงไหนของงาน
CREATE TABLE IF NOT EXISTS job_statuses (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name        text NOT NULL,
  description text,
  color       text NOT NULL DEFAULT '#64748b',
  kind        text NOT NULL DEFAULT 'open' CHECK (kind IN ('open','delivered','done','cancelled')),
  sort_order  integer NOT NULL DEFAULT 0,
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, name)
);

CREATE TABLE IF NOT EXISTS jobs (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  job_no           text NOT NULL,
  customer_id      integer NOT NULL REFERENCES customers(id),
  title            text NOT NULL,
  sign_type        text,
  material         text,
  width_cm         numeric(10,2),
  height_cm        numeric(10,2),
  quantity         integer NOT NULL DEFAULT 1,
  description      text,
  price            numeric(12,2) NOT NULL DEFAULT 0,
  status           text NOT NULL DEFAULT 'new',
  priority         text NOT NULL DEFAULT 'normal',
  assigned_to      integer REFERENCES users(id) ON DELETE SET NULL,
  due_date         date,
  install_required boolean NOT NULL DEFAULT false,
  install_address  text,
  created_by       integer REFERENCES users(id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  completed_at     timestamptz,
  UNIQUE (tenant_id, job_no)
);
CREATE INDEX IF NOT EXISTS idx_jobs_tenant_status ON jobs(tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_jobs_customer ON jobs(customer_id);
CREATE TABLE IF NOT EXISTS job_status_logs (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  job_id       integer NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  from_status  text,
  to_status    text NOT NULL,
  note         text,
  user_id      integer REFERENCES users(id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_logs_job ON job_status_logs(job_id);

CREATE TABLE IF NOT EXISTS payments (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   integer NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  job_id      integer NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  amount      numeric(12,2) NOT NULL CHECK (amount > 0),
  kind        text NOT NULL DEFAULT 'installment',
  method      text NOT NULL DEFAULT 'cash',
  note        text,
  paid_at     date NOT NULL,
  user_id     integer REFERENCES users(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_payments_tenant_date ON payments(tenant_id, paid_at);
CREATE INDEX IF NOT EXISTS idx_payments_job ON payments(job_id);

-- ===== การอัปเกรดฐานข้อมูลเดิม (รันหลังสร้างตารางครบแล้ว) =====
-- v2: ผูกงานกับ master ประเภทงาน (sign_type เก็บชื่อประเภทไว้ใช้ทำรายงาน)
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS job_type_id integer REFERENCES job_types(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_jobs_type ON jobs(job_type_id);

-- ใส่ประเภทงานเริ่มต้นให้ร้านที่ยังไม่มี
INSERT INTO job_types (tenant_id, name, description, requires_detail, sort_order)
SELECT t.id, v.name, v.description, v.requires_detail, v.sort_order
FROM tenants t CROSS JOIN (VALUES
    ${DEFAULT_JOB_TYPES_VALUES}
  ) AS v(name, description, requires_detail, sort_order)
WHERE NOT EXISTS (SELECT 1 FROM job_types jt WHERE jt.tenant_id = t.id);

-- v3: วิธีส่งมอบงาน (งานเก่าที่ติ๊ก "ต้องติดตั้ง" = ร้านเข้าติดตั้งหน้างาน)
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS delivery_method text;
UPDATE jobs SET delivery_method = 'shop_install' WHERE delivery_method IS NULL AND install_required;

-- v4: ลิงก์ Google Maps ตำแหน่งหน้างาน
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS location_url text;

-- v5: master สถานะงาน แทนสถานะแบบตายตัว (คอลัมน์ status/from_status/to_status เดิมเก็บไว้เป็นประวัติ)
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS status_id integer REFERENCES job_statuses(id);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS delivered_at timestamptz;
ALTER TABLE jobs ALTER COLUMN status DROP NOT NULL;
ALTER TABLE jobs ALTER COLUMN status DROP DEFAULT;
CREATE INDEX IF NOT EXISTS idx_jobs_status_id ON jobs(status_id);
ALTER TABLE job_status_logs ADD COLUMN IF NOT EXISTS from_status_id integer REFERENCES job_statuses(id) ON DELETE SET NULL;
ALTER TABLE job_status_logs ADD COLUMN IF NOT EXISTS to_status_id integer REFERENCES job_statuses(id) ON DELETE SET NULL;
ALTER TABLE job_status_logs ALTER COLUMN to_status DROP NOT NULL;

INSERT INTO job_statuses (tenant_id, name, description, color, kind, sort_order)
SELECT t.id, v.name, v.description, v.color, v.kind, v.sort_order
FROM tenants t CROSS JOIN (VALUES
    ${DEFAULT_JOB_STATUSES_VALUES}
  ) AS v(name, description, color, kind, sort_order)
WHERE NOT EXISTS (SELECT 1 FROM job_statuses s WHERE s.tenant_id = t.id);

UPDATE jobs j SET status_id = s.id FROM job_statuses s
WHERE j.status_id IS NULL AND s.tenant_id = j.tenant_id AND s.name = ${legacyCase('j.status')};
UPDATE jobs j SET status_id = (SELECT s.id FROM job_statuses s WHERE s.tenant_id = j.tenant_id ORDER BY s.sort_order, s.id LIMIT 1)
WHERE j.status_id IS NULL;
UPDATE jobs SET delivered_at = completed_at WHERE delivered_at IS NULL AND completed_at IS NOT NULL;
UPDATE job_status_logs l SET to_status_id = s.id FROM job_statuses s
WHERE l.to_status_id IS NULL AND l.to_status IS NOT NULL AND s.tenant_id = l.tenant_id AND s.name = ${legacyCase('l.to_status')};
UPDATE job_status_logs l SET from_status_id = s.id FROM job_statuses s
WHERE l.from_status_id IS NULL AND l.from_status IS NOT NULL AND s.tenant_id = l.tenant_id AND s.name = ${legacyCase('l.from_status')};

-- ผูกงานเดิมที่ชื่อประเภทตรงกับ master
UPDATE jobs j SET job_type_id = jt.id FROM job_types jt
WHERE j.job_type_id IS NULL AND jt.tenant_id = j.tenant_id AND jt.name = j.sign_type;

-- เปิด Row Level Security โดยไม่มี policy: ปิดการเข้าถึงตารางผ่าน Supabase Data API (anon/authenticated key)
-- แอปเชื่อมต่อด้วย role postgres ซึ่งข้าม RLS ได้ และแยกข้อมูลแต่ละร้านด้วย tenant_id ในทุก query
${TABLES.map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}
`;

module.exports = { SCHEMA, SCHEMA_VERSION, TABLES, DEFAULT_JOB_TYPES_VALUES, DEFAULT_JOB_STATUSES_VALUES };
